import Foundation
import CryptoKit

enum ClipKind: String, Codable, CaseIterable {
    case text = "Text", url = "URL", email = "Email", phone = "Phone", code = "Code", sql = "SQL", json = "JSON", note = "Long note", image = "Image", file = "File"
    var symbol: String {
        switch self {
        case .text, .note: return "text.alignleft"
        case .url: return "link"
        case .email: return "envelope"
        case .phone: return "phone"
        case .code: return "chevron.left.forwardslash.chevron.right"
        case .sql: return "externaldrive"
        case .json: return "curlybraces"
        case .image: return "photo"
        case .file: return "doc"
        }
    }
}
struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String
    var kind: ClipKind
    var createdAt = Date()
    var lastCopiedAt = Date()
    var pinned = false
    var title: String?
    var sourceApp: String?
    var sourceBundle: String?
    var assetName: String?
    var richText: Data?
    var imageData: Data?
    var imageType: String?
    var fileURLs: [String]?
    var generated = false
    var preview: String { title?.isEmpty == false ? title! : String(text.prefix(220)).replacingOccurrences(of: "\n", with: "  ") }
    var fingerprint: String {
        if let imageData { return SHA256.hash(data: imageData).map { String(format: "%02x", $0) }.joined() }
        let normalized = text.precomposedStringWithCanonicalMapping.replacingOccurrences(of: "\r\n", with: "\n")
        let bytes = Data((kind.rawValue + "\u{0}" + (assetName ?? normalized)).utf8)
        return SHA256.hash(data: bytes).map { String(format: "%02x", $0) }.joined()
    }
    func matches(_ query: String) -> Bool {
        query.split(whereSeparator: \.isWhitespace).allSatisfy { term in
            [text, title ?? "", kind.rawValue, sourceApp ?? ""].contains { $0.localizedStandardContains(String(term)) }
        }
    }
}
enum Classifier {
    static func classify(_ text: String) -> ClipKind {
        let value = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if value.hasPrefix("file://") { return .file }
        if let url = URL(string: value), ["http", "https"].contains(url.scheme?.lowercased() ?? ""), url.host != nil, !value.contains(where: \.isWhitespace) { return .url }
        if value.range(of: #"^[^\s@]+@[^\s@]+\.[^\s@]+$"#, options: .regularExpression) != nil { return .email }
        if value.range(of: #"^\+?[\d ()-]{7,22}$"#, options: .regularExpression) != nil, value.filter(\.isNumber).count >= 7 { return .phone }
        if (value.hasPrefix("{") || value.hasPrefix("[")), let data = value.data(using: .utf8), (try? JSONSerialization.jsonObject(with: data)) != nil { return .json }
        if value.range(of: #"(?is)^(select\b.+\bfrom\b|with\b.+\bas\s*\(|insert\s+into\b|update\b.+\bset\b|create\s+table\b|delete\s+from\b)"#, options: .regularExpression) != nil { return .sql }
        if value.range(of: #"(?m)(^\s*(func|function|class|import|def|const|let|var|public|private)\s+|=>|</?\w+>|\{\s*$)"#, options: .regularExpression) != nil { return .code }
        return value.count > 500 ? .note : .text
    }
}
enum PrivacyFilter {
    static let concealedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.typeit4me.clipping"]
    static func shouldIgnore(types: [String]) -> Bool { !concealedTypes.isDisjoint(with: types) }
    static func likelySecret(_ text: String) -> Bool {
        let patterns = [#"(?i)-----BEGIN .*PRIVATE KEY-----"#, #"\b(sk-[A-Za-z0-9_-]{16,}|gh[pousr]_[A-Za-z0-9]{20,}|AKIA[A-Z0-9]{16})\b"#, #"(?i)\b(password|passwd|api[_-]?key|secret|access[_-]?token)\s*[:=]\s*\S+"#, #"\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\b"#]
        return patterns.contains { text.range(of: $0, options: .regularExpression) != nil }
    }
}
struct History: Codable {
    var version = 1
    var items: [ClipItem] = []
    mutating func insert(_ item: ClipItem, limit: Int) {
        if let index = items.firstIndex(where: { $0.fingerprint == item.fingerprint }) {
            var previous = items.remove(at: index)
            previous.lastCopiedAt = item.lastCopiedAt
            previous.sourceApp = item.sourceApp ?? previous.sourceApp
            previous.richText = item.richText ?? previous.richText
            items.insert(previous, at: 0)
        } else { items.insert(item, at: 0) }
        enforceLimit(limit)
    }
    mutating func enforceLimit(_ limit: Int) {
        var count = 0
        items = items.filter { item in
            if item.pinned { return true }
            count += 1
            return count <= max(1, limit)
        }
    }
    mutating func setPinned(_ id: UUID, pinned: Bool, pinLimit: Int, historyLimit: Int) -> Bool {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return false }
        if pinned && !items[index].pinned && items.filter(\.pinned).count >= pinLimit { return false }
        var item = items.remove(at: index)
        item.pinned = pinned
        // An unpinned item becomes most recent, so the action never immediately loses it.
        items.insert(item, at: 0)
        enforceLimit(historyLimit)
        return true
    }
    var imageBytes: Int { items.reduce(0) { $0 + ($1.imageData?.count ?? 0) } }
    var totalBytes: Int { items.reduce(0) { $0 + $1.text.utf8.count + ($1.imageData?.count ?? 0) + ($1.richText?.count ?? 0) } }
    mutating func enforceStorage(imageLimit: Int, totalLimit: Int = 64 * 1024 * 1024) -> Bool {
        while imageBytes > imageLimit || totalBytes > totalLimit {
            guard let index = items.lastIndex(where: { !$0.pinned && (imageBytes <= imageLimit || $0.imageData != nil) }) else { return false }
            items.remove(at: index)
        }
        return true
    }
    var ordered: [ClipItem] { items.filter(\.pinned) + items.filter { !$0.pinned } }
}
